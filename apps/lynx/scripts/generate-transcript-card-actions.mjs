#!/usr/bin/env node
// Lift narrowly scoped upstream callbacks, keeping their bodies unchanged.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";
import { generatedFileIsFresh, writeGeneratedFile } from "./format-generated.mjs";
export const SOURCES = {
  plan: "apps/web/src/components/chat/ProposedPlanActions.tsx",
  timeline: "apps/web/src/components/chat/MessagesTimeline.tsx",
  editedFile: "apps/web/src/components/chat/EditedFileRow.tsx",
  undo: "apps/web/src/components/ChatView.tsx",
  recovery: "apps/web/src/components/chat/useChatTurnFollowUps.ts",
};
function declaration(text, file, name) {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX);
  const found = [];
  function visit(node) {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === name)
      found.push(node);
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (found.length !== 1) throw new Error(`Expected one ${name} in ${file}`);
  return { node: found[0], source };
}
function callback(text, file, name) {
  const { node, source } = declaration(text, file, name);
  if (
    !ts.isCallExpression(node.initializer) ||
    node.initializer.expression.getText(source) !== "useCallback" ||
    !ts.isArrowFunction(node.initializer.arguments[0])
  )
    throw new Error(`${name} callback changed shape`);
  return { arrow: node.initializer.arguments[0], source };
}
export function generateTranscriptCardActions(sources) {
  const planCallbacks = ["handleCopy", "handleDownload", "handleExport"]
    .map((name) => {
      const { node, source } = declaration(sources.plan, SOURCES.plan, name);
      if (!ts.isArrowFunction(node.initializer)) throw new Error(`${name} changed shape`);
      return `const ${name} = ${node.initializer.getText(source)};`;
    })
    .join("\n");
  const undo = callback(sources.undo, SOURCES.undo, "onUndoTurnFiles");
  const recovery = callback(sources.recovery, SOURCES.recovery, "onContinueFailedTurn");
  const statements = recovery.arrow.body.statements;
  const guards = statements.filter(ts.isIfStatement);
  const prompts = statements
    .filter(ts.isVariableStatement)
    .flatMap((s) => [...s.declarationList.declarations])
    .filter((d) => d.name.getText(recovery.source) === "prompt");
  if (
    guards.length !== 1 ||
    guards[0].thenStatement.getText(recovery.source).trim() !== "return false;" ||
    prompts.length !== 1 ||
    !ts.isStringLiteral(prompts[0].initializer)
  )
    throw new Error("Continuation guard/prompt changed shape");
  const guard = guards[0].expression.getText(recovery.source);
  if (!guard.includes("current.latestTurn.state") || !guard.includes("current.hasPendingUserInput"))
    throw new Error("Continuation guard dependencies changed");
  const initializer = (key, name) => {
    const { node, source } = declaration(sources[key], SOURCES[key], name);
    if (!node.initializer) throw new Error(`${name} initializer is missing`);
    return node.initializer.getText(source);
  };
  const changedFileRules = `export const MAX_VISIBLE_CHANGED_FILES = ${initializer("timeline", "MAX_VISIBLE_CHANGED_FILES")};
export const EDITED_FILE_EDITOR_ORDER = ${initializer("editedFile", "EDITED_FILE_EDITOR_ORDER")} as const;
export function changedFileUndoState(turnSummary: TurnDiffSummary, onUndoTurnFiles: unknown) {
 const checkpointTurnCount = ${initializer("timeline", "checkpointTurnCount")};
 const checkpointTurnCounts = ${initializer("timeline", "checkpointTurnCounts")};
 const canUndo = ${initializer("timeline", "canUndo")};
 return { checkpointTurnCounts, canUndo };
}`;
  return `// GENERATED by apps/lynx/scripts/generate-transcript-card-actions.mjs. Do not edit.
// Sources: ${Object.values(SOURCES).join(", ")}
// Callback bodies, continuation guard and prompt are extracted verbatim.
import type { ThreadId, TurnId } from "@synara/contracts";
import type { Thread, TurnDiffSummary } from "@synara-web/types";
import type { PendingFileUndo } from "@synara-web/components/ChatView.logic";
import { readNativeApi } from "~/nativeApi";
import { newCommandId } from "~/lib/utils";
import { toastManager } from "~/components/ui/toast";
${changedFileRules}
export function createPlanCardActions(input: {
  filename: string; markdown: string; workspaceRoot: string | undefined;
  setIsDownloading: (value: boolean) => void; setIsExporting: (value: boolean) => void;
  copyToClipboard: (value: string, context: undefined) => void;
}) {
  const {filename,markdown,workspaceRoot,setIsDownloading,setIsExporting,copyToClipboard}=input;
  ${planCallbacks}
  return {handleCopy,handleDownload,handleExport};
}
export function createUndoTurnFiles(input: {
  activeThread: Thread | undefined; isRevertingCheckpoint: boolean; hasLiveTurn: boolean;
  isSendBusy: boolean; isConnecting: boolean;
  setThreadError: (threadId: ThreadId, error: string | null) => void;
  setIsRevertingCheckpoint: (value: boolean) => void;
  setPendingFileUndo: (value: PendingFileUndo | null) => void;
}) {
  const {activeThread,isRevertingCheckpoint,hasLiveTurn,isSendBusy,isConnecting,setThreadError,setIsRevertingCheckpoint,setPendingFileUndo}=input;
  return ${undo.arrow.getText(undo.source)};
}
export const FAILED_TURN_CONTINUATION_PROMPT = ${prompts[0].initializer.getText(recovery.source)};
export function canContinueFailedTurn(current: Thread | undefined, turnId: TurnId, handlers: unknown, isServerThread: boolean) {
  return !(${guard});
}
`;
}
export function runTranscriptCardActionsGenerator(check = false) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
  const output = path.join(root, "apps/lynx/src/generated/transcriptCardActions.generated.ts");
  const result = generateTranscriptCardActions(
    Object.fromEntries(
      Object.entries(SOURCES).map(([key, file]) => [
        key,
        fs.readFileSync(path.join(root, file), "utf8"),
      ]),
    ),
  );
  if (check) {
    if (!generatedFileIsFresh(output, result)) throw new Error("Transcript card actions are stale");
  } else writeGeneratedFile(output, result);
  console.log(
    "generate-transcript-card-actions: " + (check ? "up to date" : "wrote upstream callbacks"),
  );
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  runTranscriptCardActionsGenerator(process.argv.includes("--check"));
