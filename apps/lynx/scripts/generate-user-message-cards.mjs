#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";
import { generatedFileIsFresh, writeGeneratedFile } from "./format-generated.mjs";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../../..");
export const SOURCES = {
  annotations: "apps/web/src/components/chat/BrowserAnnotationStrip.tsx",
  pullRequest: "apps/web/src/components/chat/PullRequestContextCard.tsx",
};
function initializer(text, file, name) {
  const source = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX),
    found = [];
  function visit(node) {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.name.text === name)
      found.push(node);
    ts.forEachChild(node, visit);
  }
  visit(source);
  if (found.length !== 1 || !found[0].initializer) throw Error(`Expected one ${name} in ${file}`);
  return { node: found[0].initializer, source };
}
export function generateUserMessageCards(sources) {
  const max = initializer(
    sources.annotations,
    SOURCES.annotations,
    "MAX_VISIBLE_BROWSER_ANNOTATIONS",
  );
  const icons = initializer(sources.pullRequest, SOURCES.pullRequest, "SCOPE_ICONS");
  if (!ts.isNumericLiteral(max.node) || !ts.isObjectLiteralExpression(icons.node))
    throw Error("User card rules changed shape");
  const entries = icons.node.properties.map((p) => {
    if (!ts.isPropertyAssignment(p) || !ts.isIdentifier(p.name) || !ts.isIdentifier(p.initializer))
      throw Error("Scope icon changed shape");
    return `${p.name.text}: ${JSON.stringify(p.initializer.text)}`;
  });
  return `// GENERATED by scripts/generate-user-message-cards.mjs. Do not edit.\n// Sources: ${Object.values(SOURCES).join(", ")}\nexport const MAX_VISIBLE_BROWSER_ANNOTATIONS = ${max.node.text};\nexport const USER_CONTEXT_SCOPE_ICONS = {${entries.join(",")}} as const;\n`;
}
export function run(check = false) {
  const out = path.join(root, "apps/lynx/src/generated/userMessageCards.generated.ts"),
    result = generateUserMessageCards(
      Object.fromEntries(
        Object.entries(SOURCES).map(([key, file]) => [
          key,
          fs.readFileSync(path.join(root, file), "utf8"),
        ]),
      ),
    );
  if (check) {
    if (!generatedFileIsFresh(out, result)) throw Error("User message card rules are stale");
  } else writeGeneratedFile(out, result);
  console.log("generate-user-message-cards: " + (check ? "up to date" : "wrote upstream rules"));
}
if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  run(process.argv.includes("--check"));
